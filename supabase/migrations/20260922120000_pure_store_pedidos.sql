CREATE POLICY "Colaboradores veem os pedidos da Pure Store"
  ON public.pure_store_pedidos FOR SELECT USING (public.is_colaborador(auth.uid()));
DROP POLICY IF EXISTS "Colaboradores criam pedidos da Pure Store" ON public.pure_store_pedidos;
CREATE POLICY "Colaboradores criam pedidos da Pure Store"
  ON public.pure_store_pedidos FOR INSERT WITH CHECK (public.is_colaborador(auth.uid()));
